#!/usr/bin/env python3
"""Generate the fixed 45-row Butano passive progression catalog."""

from __future__ import annotations

import argparse
import json
import struct
from pathlib import Path
from typing import Any


ENTRY_COUNT = 45
ENTRY_SIZE = 12
TABLE_OFFSET = 0x5459C8


def load_passive_content(root: Path | str) -> list[dict[str, int | str]]:
    root = Path(root)
    bank = json.loads(
        (root / "sequel/content/levels/bank.json").read_text(
            encoding="utf-8"
        )
    )
    entries = bank.get("entries", [])
    if (
        bank.get("entry_count") != ENTRY_COUNT
        or bank.get("entry_size") != ENTRY_SIZE
        or len(entries) != ENTRY_COUNT
    ):
        raise ValueError("passive progression bank must contain exactly 45 12-byte rows")
    if bank.get("table_offset") != TABLE_OFFSET:
        raise ValueError("passive progression table offset does not match ROM binding")

    result: list[dict[str, int | str]] = []
    for passive_id, source in enumerate(entries):
        if source.get("_index") != passive_id:
            raise ValueError(f"passive progression row {passive_id} is not contiguous")
        values = (
            source["target_type"],
            source["reserved1"],
            source["base_a"],
            source["base_b"],
            source["per_level_a"],
            source["per_level_b"],
            source["reserved_a"],
        )
        raw = struct.pack("<BBHHHHH", *values)
        expected_offset = TABLE_OFFSET + passive_id * ENTRY_SIZE
        if source.get("_raw_offset") != expected_offset:
            raise ValueError(
                f"passive progression row {passive_id} has a mismatched ROM offset"
            )
        result.append(
            {
                "passive_id": passive_id,
                "target_type": values[0],
                "reserved1": values[1],
                "base_a": values[2],
                "base_b": values[3],
                "per_level_a": values[4],
                "per_level_b": values[5],
                "reserved_a": values[6],
                "raw_hex": raw.hex(),
            }
        )
    return result


def _cpp_record(row: dict[str, Any]) -> str:
    return (
        "    passive_definition{ "
        f"{row['passive_id']}, {row['target_type']}, {row['reserved1']}, "
        f"{row['base_a']}, {row['base_b']}, {row['per_level_a']}, "
        f"{row['per_level_b']}, {row['reserved_a']} "
        "},"
    )


def generate_header(records: list[dict[str, Any]]) -> str:
    if len(records) != ENTRY_COUNT:
        raise ValueError("generated passive catalog must contain exactly 45 rows")
    rows = "\n".join(_cpp_record(row) for row in records)
    return f"""// Generated by tools/generate_butano_battle_passive_content.py. Do not edit.
#ifndef KONOHA_GENERATED_BATTLE_PASSIVE_CONTENT_H
#define KONOHA_GENERATED_BATTLE_PASSIVE_CONTENT_H

#include "konoha/battle_passives.h"

#include <array>

namespace konoha
{{

inline constexpr std::array<passive_definition, 45> passive_definitions = {{{{
{rows}
}}}};

}}

#endif
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "butano-sequel/game/include/konoha/"
            "generated_battle_passive_content.h"
        ),
    )
    args = parser.parse_args()
    root = args.root.resolve()
    output = args.output if args.output.is_absolute() else root / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        generate_header(load_passive_content(root)),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
