#!/usr/bin/env python3
"""Render the reverse-engineering results ledger as a viewer card.

``artifacts/reverse-results-index-v1/index.json`` is generated by the reverse
worktree's own ``tools/build_reverse_results_index.py`` and is the authoritative
answer to "what did the reverse engineering actually produce".  It carries:

* a per-category count of every artifact, note and tool,
* the evidence ledger -- one curated claim per result, with the artifact it
  rests on, and
* ``ledger_problems``: the claims that could not be substantiated.

That last field is the point: the ledger is what the reverse worktree itself
certifies, and its problem list is empty.  Showing it makes the claim
checkable instead of asserted.

Usage:
    python3 tools/build_results_viewer_ledger.py [--root .]
"""
from __future__ import annotations

import argparse
import html
import json
from pathlib import Path

FAMILY = "reverse-results-index-v1"
PRE = "../"

STATUS_LABEL = {
    "reused": "已复用",
    "verified": "已验证",
    "new": "新增",
    "partial": "部分",
    "pending": "待办",
    "blocked": "受阻",
}


def esc(value: object) -> str:
    return html.escape(str(value), quote=False)


def build(root: Path) -> str:
    index_path = root / "artifacts" / FAMILY / "index.json"
    if not index_path.is_file():
        return ""
    index = json.loads(index_path.read_text(encoding="utf-8"))
    categories = index.get("categories") or {}
    ledger = index.get("ledger") or []
    problems = index.get("ledger_problems") or []
    entries = index.get("entries") or []
    source = index.get("source") or {}

    cat_rows = "".join(
        f'<tr><td><code>{esc(name)}</code></td><td>{count:,}</td></tr>'
        for name, count in sorted(categories.items(), key=lambda kv: -kv[1])
    )
    ledger_rows = []
    for item in ledger:
        status = str(item.get("status", ""))
        source_path = str(item.get("source", ""))
        link = ""
        if source_path.startswith("artifacts/"):
            # Only link what this tree actually holds.  The ledger also covers
            # remake-side baselines that live in the other worktree, and a
            # link to a file that is not here would be a dead one.
            relative = source_path[len("artifacts/"):]
            if (root / "artifacts" / relative).is_file():
                link = (
                    f'<a class="tag tag-cyan" style="text-decoration:none;" '
                    f'href="{PRE}artifacts/{relative}">{esc(source_path)}</a>'
                )
            else:
                link = f'<code class="cc-code">{esc(source_path)}</code>'
        else:
            link = f'<code class="cc-code">{esc(source_path)}</code>'
        ledger_rows.append(
            f'                <tr><td>{esc(item.get("title", ""))}</td>'
            f'<td><code>{esc(item.get("category", ""))}</code></td>'
            f'<td><span class="tag tag-purple">'
            f'{esc(STATUS_LABEL.get(status, status))}</span></td>'
            f'<td>{esc(item.get("evidence", ""))}</td>'
            f"<td>{link}</td></tr>"
        )

    problem_block = ""
    if problems:
        problem_block = (
            '          <p class="card-desc" style="border-left:3px solid #f59e0b;'
            ' padding-left:10px;">\n'
            f"            台账中有 <strong>{len(problems)}</strong> 条结论无法落实证据，"
            "见下方索引文件。\n          </p>\n"
        )
    else:
        problem_block = (
            '          <p class="card-desc" style="border-left:3px solid #22c55e;'
            ' padding-left:10px;">\n'
            "            台账里的每一条结论都有对应证据，"
            f"<strong>未落实项为 {len(problems)}</strong>。\n          </p>\n"
        )

    commit = str(source.get("commit", ""))[:7]
    return f"""        <div class="card full-width" id="sec-reverse-ledger">
          <div class="card-head">
            <div class="card-title">逆向成果台账 (Reverse Results Ledger)</div>
            <span class="tag tag-green">{len(ledger)} 条结论 · {len(entries):,} 项成果 ·
              逆向树 {commit}</span>
          </div>
          <p class="card-desc">
            本卡直接读逆向工作树自己生成的成果索引
            <code>artifacts/{FAMILY}/index.json</code>：
            它列出逆向工程产出的<strong>每一项</strong>（产物、笔记、工具），
            以及每条结论<strong>所依据的证据</strong>。逆向树认定的未落实项就在其中。
          </p>
{problem_block}          <div class="table-container" style="max-height:200px; overflow-y:auto;">
            <table>
              <thead><tr><th>分类</th><th>项数</th></tr></thead>
              <tbody>
{cat_rows}
              </tbody>
            </table>
          </div>
          <div class="table-container" style="max-height:520px; overflow-y:auto;">
            <table>
              <thead><tr><th>结论</th><th>分类</th><th>状态</th><th>证据</th><th>来源</th></tr></thead>
              <tbody>
{chr(10).join(ledger_rows)}
              </tbody>
            </table>
          </div>
          <p class="card-desc" style="margin-top:10px;">
            完整索引（{len(entries):,} 项）见族子页
            <a class="tag tag-cyan" style="text-decoration:none;"
            href="families/{FAMILY}.html">{FAMILY}</a>，
            原始 JSON 可在板块下载包内取得。
          </p>
        </div>
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument(
        "--output", type=Path,
        default=Path("build/viewer-data/fragment-reverse-ledger.html"),
    )
    args = parser.parse_args()
    root = args.root.resolve()
    markup = build(root)
    if not markup:
        print("reverse results ledger not available")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markup, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
