#!/usr/bin/env python3
"""Generate fixed-capacity Butano battle-result content."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tools.audit_butano_reverse_provenance import provenance_block

PROVENANCE = provenance_block(
    roms=(
        (
            0x59EAE0,
            2688,
            "05cefb7a73e68d196dd4349c3eb553703d497a438468b1e8e52069d86a7096b3",
        ),
        (
            0x59F560,
            252,
            "3421ec4a6af0c2a1b5572116642ad1ec0118436052ec2bb1f09eae9a5e1cbd2c",
        ),
        (
            0x545068,
            1008,
            "6f080fcdbcd99f89a223bf07fe96be01365f2bffbb8bb74e0b7439839b8c8cd9",
        ),
    ),
    not_applicable=(
        "no signed reverse manifest records the reward table 0x59EAE0, the "
        "experience threshold table 0x59F560 or the character stats table "
        "0x545068",
    ),
)

# The products this generator writes.  The provenance auditor reads this
# registry to learn the product set; it never guesses the set from a file
# name pattern.
GENERATED_PRODUCTS = (
    "butano-sequel/game/include/konoha/"
    "generated_battle_result_content.h",
)


CHARACTER_COUNT = 63
REWARD_RECORD_COUNT = 112
SCENARIO_REWARD_COUNT = 48


def _load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def load_battle_result_content(root: Path) -> dict[str, Any]:
    results = _load_json(
        root / "sequel/content/battle-results/bank.json"
    )
    growth = _load_json(
        root / "sequel/content/character-stats/bank.json"
    )
    rewards = results["reward_records"]
    thresholds = results["experience_thresholds"]
    mapping = results["scenario_reward_record_indices"]
    growth_entries = growth["entries"]
    if len(rewards) != REWARD_RECORD_COUNT:
        raise ValueError("unexpected battle reward record count")
    if len(thresholds) != CHARACTER_COUNT:
        raise ValueError("unexpected experience threshold count")
    if len(mapping) != SCENARIO_REWARD_COUNT:
        raise ValueError("unexpected scenario reward mapping count")
    if len(growth_entries) != CHARACTER_COUNT:
        raise ValueError("unexpected character growth record count")
    for expected, row in enumerate(rewards):
        if row["record_id"] != expected:
            raise ValueError("non-contiguous battle reward records")
    for expected, row in enumerate(thresholds):
        if row["character_id"] != expected:
            raise ValueError("non-contiguous experience thresholds")
    for expected, row in enumerate(growth_entries):
        if row["character_id"] != expected:
            raise ValueError("non-contiguous character growth records")
    return {
        "rewards": rewards,
        "thresholds": thresholds,
        "mapping": mapping,
        "growth": growth_entries,
    }


def _array(values: list[int]) -> str:
    return ", ".join(str(value) for value in values)


def generate_header(content: dict[str, Any]) -> str:
    rewards = []
    for row in content["rewards"]:
        rewards.append(
            "battle_reward_definition{ "
            f"{row['mission_experience']}, "
            f"{row['round_bonus_experience']}, "
            f"{row['round_limit']}, "
            "std::array<std::uint16_t, 9>{{ "
            f"{_array(row['postbattle_words'])} "
            "}} }"
        )
    thresholds = [
        "experience_threshold_definition{ "
        f"{row['per_level_increment']}, "
        f"{row['base_threshold']} }}"
        for row in content["thresholds"]
    ]
    growth = [
        "character_growth_definition{ "
        f"{row['template_0e_growth']}, "
        f"{row['template_08_growth']}, "
        f"{row['template_02_growth']}, "
        f"{row['template_03_growth']}, "
        f"{row['template_04_growth']}, "
        f"{row['template_05_growth']}, "
        f"{row['template_06_growth']} }}"
        for row in content["growth"]
    ]
    return f"""// Generated by tools/generate_butano_battle_result_content.py. Do not edit.
{PROVENANCE}
#ifndef KONOHA_GENERATED_BATTLE_RESULT_CONTENT_H
#define KONOHA_GENERATED_BATTLE_RESULT_CONTENT_H

#include "konoha/battle_progression.h"
#include "konoha/battle_result_content.h"

#include <array>
#include <cstdint>

namespace konoha
{{

inline constexpr std::array<battle_reward_definition, {len(rewards)}>
        battle_reward_definitions = {{{{
    {",\n    ".join(rewards)}
}}}};

inline constexpr std::array<experience_threshold_definition, {len(thresholds)}>
        experience_threshold_definitions = {{{{
    {",\n    ".join(thresholds)}
}}}};

inline constexpr std::array<character_growth_definition, {len(growth)}>
        character_growth_definitions = {{{{
    {",\n    ".join(growth)}
}}}};

inline constexpr std::array<std::uint8_t, {len(content["mapping"])}>
        scenario_reward_record_indices = {{{{
    {_array(content["mapping"])}
}}}};

}}

#endif
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "butano-sequel/game/include/konoha/"
            "generated_battle_result_content.h"
        ),
    )
    args = parser.parse_args()
    root = args.root.resolve()
    output = args.output
    if not output.is_absolute():
        output = root / output
    content = load_battle_result_content(root)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generate_header(content), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
