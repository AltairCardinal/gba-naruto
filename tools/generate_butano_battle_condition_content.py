#!/usr/bin/env python3
"""Generate all fixed Butano battle-condition variants from the bound ROM bank."""

from __future__ import annotations

import argparse
import hashlib
import struct
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tools.audit_butano_reverse_provenance import provenance_block

PROVENANCE = provenance_block(
    sources=(
        (
            "rom-battle-condition-records-v1",
            "c9ea59da9e2f870446f51a0424317ca6dfb23daa67a348bb0a78093b86d3c079",
        ),
    ),
    roms=(
        (
            0x594758,
            9588,
            "0d6e137011aa4e97c5b5d165f1939b7fb0b33235b9b20fceb1566b485dc35bf4",
        ),
    ),
)

# The products this generator writes.  The provenance auditor reads this
# registry to learn the product set; it never guesses the set from a file
# name pattern.
GENERATED_PRODUCTS = (
    "butano-sequel/game/include/konoha/"
    "generated_battle_condition_content.h",
)


ROM_BASE = 0x08000000
RECORD_BASE = 0x08594758
BATTLE_COUNT = 47
BATTLE_STRIDE = 0xCC
VARIANT_COUNT = 3
VARIANT_STRIDE = 0x44
HEADER_SIZE = 4
GROUP_SIZE = 0x20
PREDICATE_STRIDE = 8
RECORDS_SHA256 = "0d6e137011aa4e97c5b5d165f1939b7fb0b33235b9b20fceb1566b485dc35bf4"

TYPE_NAMES = {
    0: "empty",
    1: "no_valid_unit_for_side",
    2: "round_limit_reached",
    3: "no_valid_character_for_side",
    4: "unused_4",
    5: "unused_5",
    6: "object_slot_inactive",
    7: "side_hp_sum_greater",
    8: "side_unit_count_greater",
    9: "side_resolved_object_count_greater",
}


def _predicate(rom: bytes, offset: int) -> dict[str, int]:
    condition_type, arg0, arg1, reserved, script_address = struct.unpack_from(
        "<BBBBI", rom, offset
    )
    if condition_type not in TYPE_NAMES:
        raise ValueError(f"unknown condition type {condition_type} at 0x{offset:06X}")
    if reserved != 0:
        raise ValueError(f"nonzero reserved byte at 0x{offset:06X}")
    return {
        "type": condition_type,
        "arg0": arg0,
        "arg1": arg1,
        "script_address": script_address,
    }


def load_condition_content(root: Path | str) -> list[list[dict]]:
    root = Path(root)
    rom = (root / "rom" / "base.gba").read_bytes()
    record_offset = RECORD_BASE - ROM_BASE
    record_size = BATTLE_COUNT * BATTLE_STRIDE
    records = rom[record_offset : record_offset + record_size]
    if len(records) != record_size:
        raise ValueError("battle condition bank is truncated")
    if hashlib.sha256(records).hexdigest() != RECORDS_SHA256:
        raise ValueError("battle condition bank SHA-256 mismatch")

    battles = []
    for battle_id in range(BATTLE_COUNT):
        variants = []
        for variant_id in range(VARIANT_COUNT):
            offset = (
                record_offset
                + battle_id * BATTLE_STRIDE
                + variant_id * VARIANT_STRIDE
            )

            def group(group_offset: int) -> list[dict[str, int]]:
                return [
                    _predicate(rom, offset + group_offset + slot * PREDICATE_STRIDE)
                    for slot in range(4)
                ]

            variants.append(
                {
                    "header": list(rom[offset : offset + HEADER_SIZE]),
                    "win": group(HEADER_SIZE),
                    "lose": group(HEADER_SIZE + GROUP_SIZE),
                }
            )
        battles.append(variants)
    return battles


def _cpp_predicate(predicate: dict[str, int]) -> str:
    return (
        "battle_condition_predicate{ "
        f"battle_condition_type::{TYPE_NAMES[predicate['type']]}, "
        f"{predicate['arg0']}, {predicate['arg1']}, "
        f"0x{predicate['script_address']:08X}U "
        "}"
    )


def _cpp_group(group: list[dict[str, int]]) -> str:
    values = ", ".join(_cpp_predicate(predicate) for predicate in group)
    return f"std::array<battle_condition_predicate, 4>{{{{ {values} }}}}"


def _cpp_variant(variant: dict) -> str:
    header = ", ".join(str(value) for value in variant["header"])
    return (
        "        battle_condition_variant{ "
        f"std::array<std::uint8_t, 4>{{{{ {header} }}}}, "
        f"{_cpp_group(variant['win'])}, "
        f"{_cpp_group(variant['lose'])} "
        "},"
    )


def generate_header(root: Path | str) -> str:
    battles = load_condition_content(root)
    battle_rows = []
    for variants in battles:
        variant_rows = "\n".join(_cpp_variant(variant) for variant in variants)
        battle_rows.append(
            "    std::array<battle_condition_variant, 3>{{\n"
            f"{variant_rows}\n"
            "    }},"
        )
    rows = "\n".join(battle_rows)
    return f"""// Generated by tools/generate_butano_battle_condition_content.py. Do not edit.
{PROVENANCE}
#ifndef KONOHA_GENERATED_BATTLE_CONDITION_CONTENT_H
#define KONOHA_GENERATED_BATTLE_CONDITION_CONTENT_H

#include "konoha/battle_conditions.h"

#include <array>

namespace konoha
{{

inline constexpr std::array<std::array<battle_condition_variant, 3>, 47>
        battle_condition_variants = {{{{
{rows}
}}}};

}}

#endif
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "butano-sequel/game/include/konoha/generated_battle_condition_content.h"
        ),
    )
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate_header(args.root), encoding="utf-8")
    print(f"generated {args.output} with 47 battles x 3 variants")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
